import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { Client } from "pg";
import { randomUUID } from "node:crypto";
import { copyConsistentSnapshot, quoteIdentifier, verifySnapshotManifest } from "./snapshot-copy";

// Opt-in only. This suite never reads or writes the real DEV application DB.
const integration = process.env.CS2_SNAPSHOT_TEST_ADMIN_URL ? describe : describe.skip;
integration("transactional snapshot copy on disposable databases", () => {
  let admin: Client, source: Client, writer: Client, target: Client;
  const suffix = randomUUID().replaceAll("-", "");
  const sourceName = `cs2_stats_test_source_${suffix}`, targetName = `cs2_stats_test_target_${suffix}`;
  beforeAll(async () => {
    const url = new URL(process.env.CS2_SNAPSHOT_TEST_ADMIN_URL!);
    if (!["localhost", "127.0.0.1"].includes(url.hostname) || url.pathname !== "/postgres") throw new Error("Test admin must be local /postgres.");
    admin = new Client({ connectionString: url.href }); await admin.connect();
    await admin.query(`CREATE DATABASE ${quoteIdentifier(sourceName)}`);
    await admin.query(`CREATE DATABASE ${quoteIdentifier(targetName)}`);
    url.pathname = "/" + sourceName;
    source = new Client({ connectionString: url.href }); writer = new Client({ connectionString: url.href });
    url.pathname = "/" + targetName; target = new Client({ connectionString: url.href });
    await Promise.all([source.connect(), writer.connect(), target.connect()]);
    for (const c of [source, target]) await c.query(`
      CREATE TABLE parent(id text PRIMARY KEY, value text, json jsonb, stamp timestamp(6), amount numeric(30,8));
      CREATE TABLE child(id text PRIMARY KEY, parent_id text NOT NULL REFERENCES parent(id));
      INSERT INTO parent VALUES ('old','before','null','2026-10-30 12:13:14.123456',12345678901234567890.12345678);
      INSERT INTO parent VALUES ('sqlnull',NULL,NULL,NULL,NULL);
      INSERT INTO child VALUES ('child','old');`);
  });
  afterAll(async () => {
    await Promise.allSettled([source?.end(), writer?.end(), target?.end()]);
    if (admin) {
      // Only names generated by this suite; no computed user target is dropped.
      for (const name of [sourceName, targetName]) {
        if (!/^cs2_stats_test_(source|target)_[a-f0-9]{32}$/.test(name)) throw new Error("Unsafe cleanup target");
        await admin.query(`DROP DATABASE IF EXISTS ${quoteIdentifier(name)}`);
      }
      await admin.end();
    }
  });
  it("pins counts and content while another connection inserts and updates", async () => {
    const manifest = await copyConsistentSnapshot(source, target, {
      tables: ["parent", "child"],
      beforeCopy: async () => {
        await writer.query("UPDATE parent SET value='after' WHERE id='old'");
        await writer.query("INSERT INTO parent(id,value) VALUES ('new','concurrent')");
      },
    });
    expect(manifest.effectiveRole).toBe("pg_read_all_data");
    expect(manifest.readOnly).toBe(true);
    expect(manifest.tables.parent.count).toBe(2);
    expect((await target.query("SELECT value FROM parent WHERE id='old'")).rows[0].value).toBe("before");
    expect((await target.query("SELECT count(*)::int n FROM parent")).rows[0].n).toBe(2);
    const row = (await target.query("SELECT json::text,stamp::text,amount::text FROM parent WHERE id='old'")).rows[0];
    expect(row).toEqual({ json: "null", stamp: "2026-10-30 12:13:14.123456", amount: "12345678901234567890.12345678" });
    expect((await target.query("SELECT json IS NULL n FROM parent WHERE id='sqlnull'")).rows[0].n).toBe(true);
  });
  it("rolls back all destination tables on a mid-copy failure", async () => {
    const before = (await target.query("SELECT row_to_json(p) v FROM parent p ORDER BY id")).rows;
    await expect(copyConsistentSnapshot(source, target, {
      tables: ["parent", "child"], afterTable: async () => { throw new Error("injected disconnect"); },
    })).rejects.toThrow("injected disconnect");
    expect((await target.query("SELECT row_to_json(p) v FROM parent p ORDER BY id")).rows).toEqual(before);
    expect((await target.query("SELECT count(*)::int n FROM child")).rows[0].n).toBe(1);
  });
  it("rejects schema mismatch before touching destination rows", async () => {
    await target.query("ALTER TABLE child ADD COLUMN incompatible text");
    await expect(copyConsistentSnapshot(source, target, { tables: ["parent", "child"] })).rejects.toThrow("Schema mismatch");
    expect((await target.query("SELECT value FROM parent WHERE id='old'")).rows[0].value).toBe("before");
    await target.query("ALTER TABLE child DROP COLUMN incompatible");
  });
  it("detects content corruption even when the row count is unchanged", async () => {
    await target.query(`CREATE FUNCTION corrupt() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.value='corrupted'; RETURN NEW; END $$;
      CREATE TRIGGER corrupt BEFORE INSERT ON parent FOR EACH ROW EXECUTE FUNCTION corrupt();`);
    await expect(copyConsistentSnapshot(source, target, { tables: ["parent", "child"] })).rejects.toThrow("Manifest mismatch");
    expect((await target.query("SELECT value FROM parent WHERE id='old'")).rows[0].value).toBe("before");
    await target.query("DROP TRIGGER corrupt ON parent; DROP FUNCTION corrupt()");
  });
  it("can repeat safely and preserves foreign keys", async () => {
    const a = await copyConsistentSnapshot(source, target, { tables: ["parent", "child"] });
    const b = await copyConsistentSnapshot(source, target, { tables: ["parent", "child"] });
    expect(a.tables).toEqual(b.tables);
    expect(await verifySnapshotManifest(target, b)).toEqual(["parent", "child"]);
    await target.query("UPDATE parent SET value='drift' WHERE id='old'");
    await expect(verifySnapshotManifest(target, b)).rejects.toThrow("Manifest mismatch");
    expect((await target.query("SELECT count(*)::int n FROM child c LEFT JOIN parent p ON p.id=c.parent_id WHERE p.id IS NULL")).rows[0].n).toBe(0);
  });
});
